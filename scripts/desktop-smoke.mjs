import { spawn } from 'node:child_process';
import { mkdir, mkdtemp, writeFile, appendFile, readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
await mkdir('.cx/observer-tests',{recursive:true});await mkdir('artifacts/observer',{recursive:true});
const root=await mkdtemp(resolve('.cx/observer-tests/native-'));
const path=join(root,'rollout-parent.jsonl'),childPath=join(root,'rollout-child.jsonl');
const row=(type,payload)=>JSON.stringify({timestamp:new Date().toISOString(),type,payload})+'\n';
await writeFile(path,row('session_meta',{id:'fixture-parent'})+row('event_msg',{type:'task_started',turn_id:'t'}));
await writeFile(childPath,row('session_meta',{id:'fixture-child',source:{subagent:{thread_spawn:{parent_thread_id:'fixture-parent'}}}})+row('event_msg',{type:'task_started',turn_id:'t'}));
const screenshot=resolve('artifacts/observer/fixture-en.png'),checks=resolve('artifacts/observer/native-checks.json');
const native=spawn(resolve('dist/Office-Smoke.exe'),['--lang','en','--capture',screenshot,'--seconds','9'],{stdio:'ignore',env:{...process.env,CX_SESSIONS_DIR:root,CX_NODE_EXE:process.execPath,CX_SMOKE_RESULT:checks}});
const exited=new Promise((res,rej)=>{native.once('exit',res);native.once('error',rej);});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
await sleep(1100);await appendFile(path,row('event_msg',{type:'exec_approval_request',turn_id:'t'}));
await sleep(1200);await appendFile(path,row('event_msg',{type:'exec_command_begin',turn_id:'t'}));
await sleep(1200);await appendFile(path,row('event_msg',{type:'item_completed',turn_id:'t',item:{type:'FileChange'}}));
await sleep(1200);await appendFile(path,row('event_msg',{type:'task_complete',turn_id:'t'}));
assert.equal(await exited,0);
const state=JSON.parse(await readFile(screenshot.replace('.png','.json'),'utf8'));
for(const a of ['working','approval','running','editing','finished'])assert.ok(state.activities.includes(a),a);
assert.equal(state.sessionCount,2);assert.equal(state.status,'watching');
console.log('Native fixture: lifecycle, approval, two sessions, explicit child, language/pin/motion, resize/minimize/close passed.');
console.log(await readFile(checks,'utf8'));
